#!/usr/bin/env -S deno run -A

/**
 * NodX code generator for TypeScript.
 *
 * Fetches the reference data directly from the canonical NodX repository and
 * generates (in memory, without touching `data/` on disk):
 *
 * - `src/generated/elements.ts` — one function per HTML element.
 * - `src/generated/attributes.ts` — one function per HTML attribute.
 * - `src/generated/elements.test.ts` — an exhaustive test per element.
 * - `src/generated/attributes.test.ts` — an exhaustive test per attribute.
 *
 * The naming rules (PascalCase conversion, collision resolution) live in
 * {@link ./codegen_helpers.ts} and are tested separately.
 *
 * Usage: `deno task codegen` or implicitly via `deno task build`.
 *
 * @module
 */

import { join } from "@std/path";
import {
  conflictsWithKeyword,
  createFuncName,
  hasDuplicateName,
  shadowsGlobal,
  stripGlobMarker,
  toPascalCase,
} from "./codegen_helpers.ts";
import type { Attr, El } from "./codegen_helpers.ts";
import { fromRoot } from "./helpers.ts";

/** Canonical remote location of the NodX reference data. */
const REMOTE_BASE = "https://raw.githubusercontent.com/varavelio/nodx/main/data";

/** Output directory for the generated modules. */
const OUT_DIR = fromRoot("./src/generated/");

/** Header prepended to every generated file. */
function header(kind: string): string[] {
  return [
    `// Code generated by NodX codegen (${kind}). DO NOT EDIT.`,
    `//`,
    `// Source data: https://github.com/varavelio/nodx/blob/main/data`,
    ``,
  ];
}

async function fetchJson<T>(file: string): Promise<T> {
  const url = `${REMOTE_BASE}/${file}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.json() as Promise<T>;
}

/**
 * Resolves the final function name for a raw element/attribute name.
 *
 * A suffix (`El` or `Attr`) is appended when any of the following holds:
 *
 * 1. Another element or attribute shares the same raw name.
 * 2. The final identifier would collide with a reserved keyword.
 * 3. The final identifier would shadow an ECMAScript global constructor
 *    (see {@linkcode PRESERVED_GLOBALS}).
 */
function resolveFuncName(
  name: string,
  type: "El" | "Attr",
  els: readonly El[],
  attrs: readonly Attr[],
  keywords: readonly string[],
): ReturnType<typeof createFuncName> {
  const attrName = stripGlobMarker(name);
  const baseName = toPascalCase(attrName);
  const conflict = hasDuplicateName(name, els, attrs) ||
    conflictsWithKeyword(baseName, keywords) ||
    shadowsGlobal(baseName);
  return createFuncName(name, type, conflict);
}

/**
 * Builds a JSDoc block with a description and a runnable example.
 *
 * @param description The description from the reference data.
 * @param exampleLines The body of the ```ts example block.
 */
function jsdoc(description: string, exampleLines: string[]): string[] {
  return [
    `/**`,
    ` * ${description}`,
    ` *`,
    ` * @example Usage`,
    ` * \`\`\`ts`,
    ...exampleLines.map((line) => ` * ${line}`),
    ` * \`\`\``,
    ` */`,
  ];
}

function generateElements(
  els: readonly El[],
  attrs: readonly Attr[],
  keywords: readonly string[],
): string {
  const lines = header("elements");

  lines.push(
    `import { El, ElVoid } from "../element.ts";`,
    `import type { ElementNode } from "../element.ts";`,
    `import type { NodeChild } from "../node.ts";`,
    ``,
  );

  for (const el of els) {
    const func = resolveFuncName(el.name, "El", els, attrs, keywords);
    const factory = el.isVoid ? "ElVoid" : "El";

    const call = el.isVoid
      ? `${func.name}(Id("1"))`
      : `${func.name}(Id("1"), Text("Hello World!"))`;
    const output = el.isVoid
      ? `<${el.name} id="1">`
      : `<${el.name} id="1">Hello World!</${el.name}>`;

    lines.push(
      ...jsdoc(el.description, [
        `import { ${func.name}, Id, Text } from "@varavel/nodx";`,
        ``,
        `const node = ${call};`,
        `// Renders as: ${output}`,
      ]),
    );
    lines.push(
      `export function ${func.name}(...children: NodeChild[]): ElementNode {`,
      `  return ${factory}("${el.name}", ...children);`,
      `}`,
      ``,
    );
  }

  return lines.join("\n");
}

function generateAttributes(
  els: readonly El[],
  attrs: readonly Attr[],
  keywords: readonly string[],
): string {
  const lines = header("attributes");

  lines.push(
    `import { Attr, AttrBool, AttrList } from "../attribute.ts";`,
    `import type { AttributeNode } from "../attribute.ts";`,
    `import type { AttributeValue, Node } from "../node.ts";`,
    ``,
  );

  for (const attr of attrs) {
    const func = resolveFuncName(attr.name, "Attr", els, attrs, keywords);

    if (func.isGlob) {
      // Glob attributes like `data-*` take a dynamic key that is appended
      // to the prefix (`data-`).
      const prefixed = `${func.attrName}${"key"}`;
      lines.push(
        ...jsdoc(attr.description, [
          `import { ${func.name} } from "@varavel/nodx";`,
          ``,
          `const node = ${func.name}("key", "value");`,
          `// Renders as: ${prefixed}="value"`,
        ]),
      );
      lines.push(
        `export function ${func.name}(`,
        `  key: string,`,
        `  value: AttributeValue,`,
        `): AttributeNode {`,
        `  return Attr(\`${func.attrName}\${key}\`, value);`,
        `}`,
        ``,
      );
      continue;
    }

    if (attr.isBoolean) {
      lines.push(
        ...jsdoc(attr.description, [
          `import { ${func.name}, Input } from "@varavel/nodx";`,
          ``,
          `const node = Input(${func.name}(true));`,
          `// Renders as: <input ${attr.name}>`,
          ``,
          "// When the value is `false`, the attribute is omitted entirely:",
          `const omitted = Input(${func.name}(false));`,
          `// Renders as: <input>`,
        ]),
      );
      lines.push(
        `export function ${func.name}(value: boolean): Node {`,
        `  return AttrBool("${attr.name}", value);`,
        `}`,
        ``,
      );
      continue;
    }

    if (attr.isList) {
      lines.push(
        ...jsdoc(attr.description, [
          `import { ${func.name} } from "@varavel/nodx";`,
          ``,
          `const node = ${func.name}("value-a value-b", "value-c");`,
          `// Renders as: ${attr.name}="value-a value-b value-c"`,
        ]),
      );
      lines.push(
        `export function ${func.name}(`,
        `  ...values: readonly AttributeValue[],`,
        `): AttributeNode {`,
        `  return AttrList("${attr.name}", ...values);`,
        `}`,
        ``,
      );
      continue;
    }

    lines.push(
      ...jsdoc(attr.description, [
        `import { ${func.name} } from "@varavel/nodx";`,
        ``,
        `const node = ${func.name}("value");`,
        `// Renders as: ${attr.name}="value"`,
      ]),
    );
    lines.push(
      `export function ${func.name}(value: AttributeValue): AttributeNode {`,
      `  return Attr("${attr.name}", value);`,
      `}`,
      ``,
    );
  }

  return lines.join("\n");
}

/** Generates an exhaustive render test for every element. */
function generateElementsTest(
  els: readonly El[],
  attrs: readonly Attr[],
  keywords: readonly string[],
): string {
  const names = new Set<string>(["Id", "Text"]);
  const cases: string[] = [];

  for (const el of els) {
    const func = resolveFuncName(el.name, "El", els, attrs, keywords);
    names.add(func.name);

    const call = el.isVoid
      ? `${func.name}(Id("1"))`
      : `${func.name}(Id("1"), Text("Hello World!"))`;
    const output = el.isVoid
      ? `<${el.name} id="1">`
      : `<${el.name} id="1">Hello World!</${el.name}>`;

    cases.push(
      ``,
      `Deno.test("${func.name} renders its HTML element", () => {`,
      `  assertEquals(`,
      `    ${call}.render(),`,
      `    \`${output}\`,`,
      `  );`,
      `});`,
    );
  }

  const imports = [...names].sort();
  return [
    ...header("element tests"),
    `import { assertEquals } from "@std/assert";`,
    `import {`,
    ...imports.map((name) => `  ${name},`),
    `} from "../index.ts";`,
    ``,
    ...cases,
  ].join("\n");
}

/** Generates an exhaustive render test for every attribute. */
function generateAttributesTest(
  els: readonly El[],
  attrs: readonly Attr[],
  keywords: readonly string[],
): string {
  const names = new Set<string>();
  const cases: string[] = [];

  for (const attr of attrs) {
    const func = resolveFuncName(attr.name, "Attr", els, attrs, keywords);
    names.add(func.name);

    if (func.isGlob) {
      cases.push(
        ``,
        `Deno.test("${func.name} renders its dynamic attribute", () => {`,
        `  assertEquals(`,
        `    ${func.name}("key", "value").render(),`,
        `    \`${func.attrName}key="value"\`,`,
        `  );`,
        `});`,
      );
      continue;
    }

    if (attr.isBoolean) {
      cases.push(
        ``,
        `Deno.test("${func.name} renders as a boolean attribute", () => {`,
        `  assertEquals(${func.name}(true).render(), \`${attr.name}\`);`,
        `  assertEquals(${func.name}(false).render(), "");`,
        `});`,
      );
      continue;
    }

    if (attr.isList) {
      cases.push(
        ``,
        `Deno.test("${func.name} joins its values into a token list", () => {`,
        `  assertEquals(`,
        `    ${func.name}("value-a value-b", "", "value-c").render(),`,
        `    \`${attr.name}="value-a value-b value-c"\`,`,
        `  );`,
        `});`,
      );
      continue;
    }

    cases.push(
      ``,
      `Deno.test("${func.name} renders its attribute", () => {`,
      `  assertEquals(`,
      `    ${func.name}("value").render(),`,
      `    \`${attr.name}="value"\`,`,
      `  );`,
      `});`,
    );
  }

  const imports = [...names].sort();
  return [
    ...header("attribute tests"),
    `import { assertEquals } from "@std/assert";`,
    `import {`,
    ...imports.map((name) => `  ${name},`),
    `} from "../index.ts";`,
    ``,
    ...cases,
  ].join("\n");
}

async function write(path: string, content: string): Promise<void> {
  const fullPath = join(OUT_DIR, path);
  await Deno.writeTextFile(fullPath, content);
  console.log(`Generated ${fullPath}`);
}

export async function runCodegen(): Promise<void> {
  const els = await fetchJson<El[]>("elements.json");
  const attrs = await fetchJson<Attr[]>("attributes.json");
  const keywordFiles = await fetchJson<Record<string, string[]>>("keywords.json");
  const keywords = keywordFiles["TypeScript"] ?? [];

  await Deno.mkdir(OUT_DIR, { recursive: true });

  await write("elements.ts", generateElements(els, attrs, keywords));
  await write("attributes.ts", generateAttributes(els, attrs, keywords));
  await write("elements.test.ts", generateElementsTest(els, attrs, keywords));
  await write(
    "attributes.test.ts",
    generateAttributesTest(els, attrs, keywords),
  );

  // Format the generated files so they always match the repository style.
  const command = new Deno.Command(Deno.execPath(), {
    args: ["fmt", OUT_DIR],
    stdin: "null",
    stdout: "inherit",
    stderr: "inherit",
  });
  const status = await command.spawn().status;

  if (!status.success) {
    console.error("Failed to format the generated files.");
    Deno.exit(1);
  }
}
